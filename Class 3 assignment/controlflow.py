# Control flow in programming dictates the order in which statements are executed based on conditions, loops or function calls

# Types of Control Flow in Python

# Sequential Flow

print("Step 1")
print("Step 2")
print("Step 3")

# Conditional Statements

# if statement

age = 28
if age >=20:
    print("You are an adult")

# if else statement

is_raining = True

if is_raining:
    print("Take an umbrella.")

else:
    print("Enjoy the sunshine.")    


# if...elif...else statement

score = 45

if score >= 78:
    print("Grade A")

elif score >= 50:
    print("Grade B")

else:
    print("Grade C")        


# Loops

# for loop

for i in range(5):
    print(f"Number: {i}")   

# for loop over a list

colors = ["purple", "margenda", "ice blue"] 
for color in colors:
    print(color)    




