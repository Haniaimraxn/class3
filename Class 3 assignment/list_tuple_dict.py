# List _Tuple_ Dict

# List
# A list is an ordered, mutable (changable) collection items.

# Defigned using square brackets [].

# Creating a list 
fruits = ["guava", "cherry", "pineapple"]
print(fruits[1])
fruits[1] = "orange"
print(fruits)

# Access item in a list

fruits = ["guava", " cherry", "pineapple"]
print(fruits[1])

# Tuple
# A tuple is an ordered, immutable (unchangable) collection of items.
# Defined using parenthesis ().

colors = ("purple", "green", "white")
print(colors[0])

# Access item in a Tuple
# Tuples also using indexing (like lists).

colors = ("purple", "green", "white")

# Dictionary
# A dictionary is an unordered collection of key-value pairs.
# Defined using curly braces {}

person = {"name": "Noreh", "age" : "20", "city": "New York"}
print(person["name"])
print(person["age"])
